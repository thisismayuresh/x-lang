TSC = shutil.which("tsc") or shutil.which("npx")


def emit_ts(source: str) -> str:
    """Load *source* through the real module loader and emit TypeScript."""
    with tempfile.TemporaryDirectory() as temporary_directory:
        project_root = Path(temporary_directory)
        source_file = project_root / "main.x"
        source_file.write_text(source, encoding="utf-8")
        loader = ModuleLoader(project_root, XConfig())
        program = loader.load_program(source_file)
        assert not loader.errors, loader.errors
        return emit(program, "typescript", source_name="main.x")


class TypeScriptEmitTests(unittest.TestCase):
    def assert_valid_typescript(self, source: str) -> str:
        """Emit *source* and, when tsc is available, parse-check the result."""
        output = emit_ts(source)
        if TSC is None:
            self.skipTest("tsc not available")
        with tempfile.TemporaryDirectory() as temporary_directory:
            output_file = Path(temporary_directory) / "out.ts"
            output_file.write_text(output, encoding="utf-8")
            result = subprocess.run(
                [
                    TSC,
                    "--noEmit",
                    "--target",
                    "es2020",
                    "--lib",
                    "es2020,dom",
                    "--skipLibCheck",
                    "--noResolve",
                    str(output_file),
                ],
                capture_output=True,
                text=True,
            )
            syntax_errors = [
                line
                for line in result.stdout.splitlines()
                if "error TS1" in line
            ]
            self.assertEqual(syntax_errors, [], "\n".join(result.stdout.splitlines()[:20]))
        return output

