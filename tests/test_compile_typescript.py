    # ── try / resources ──────────────────────────────────────────────────

    def test_try_catch_finally(self):
        output = emit_ts(
            "function main() {\n"
            "    try { work(); }"
            " catch (Exception e) { handle(e); }"
            " finally { cleanup(); }"
            "}"
        )
        self.assertIn("try {", output)
        self.assertIn("catch (e: Exception) {", output)
        self.assertIn("finally {", output)

    def test_try_with_resources_closes_before_catch(self):
        output = emit_ts(
            "function main() {\n"
            "    try (let r = openFile(\"a.txt\")) {\n"
            "        work();\n"
            "    } catch (Exception e) {\n"
            "        handle(e);\n"
            "    } finally {\n"
            "        cleanup();\n"
            "    }\n"
            "}"
        )
        # The resource closes in an inner finally wrapped around the body, so
        # the outer catch/finally attach to the outer try, not the inner one.
        inner_close = output.index("r.close();")
        catch_index = output.index("catch (e: Exception)")
        finally_index = output.rindex("finally {")
        self.assertLess(inner_close, catch_index)
        self.assertLess(catch_index, finally_index)
        self.assertIn("let r = openFile(\"a.txt\");", output)

    def test_try_with_multiple_resources_closes_in_reverse(self):
        output = emit_ts(
            "function main() {\n"
            "    try (let a = first(), const b = second()) {\n"
            "        work();\n"
            "    }"
            "}"
        )
        self.assertIn("let a = first();", output)
        self.assertIn("const b = second();", output)
        self.assertLess(output.index("b.close();"), output.index("a.close();"))

