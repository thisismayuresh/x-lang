class CompileRegistryTests(unittest.TestCase):
    def test_typescript_is_a_supported_target(self):
        self.assertIn("typescript", SUPPORTED_TARGETS)

    def test_unknown_target_raises_codegen_error(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            project_root = Path(temporary_directory)
            source_file = project_root / "main.x"
            source_file.write_text("function main() { }", encoding="utf-8")
            loader = ModuleLoader(project_root, XConfig())
            program = loader.load_program(source_file)
            with self.assertRaises(CodegenError) as caught:
                emit(program, "rust", source_name="main.x")
